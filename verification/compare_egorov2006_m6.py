#!/usr/bin/env python
"""Egorov, Fedorov & Soudakov (2006) Mach 6 flat-plate second-mode verification.

Target
------
  I. V. Egorov, A. V. Fedorov, V. G. Soudakov, "Direct numerical simulation of
  disturbances generated by periodic suction-blowing in a hypersonic boundary
  layer", Theoretical and Computational Fluid Dynamics 20, 41-54 (2006),
  DOI 10.1007/s00162-006-0027-9.

  They report that, for small forcing amplitudes, the *second-mode growth rate*
  obtained by 2-D DNS over a Mach-6 flat plate agrees with linear stability
  theory (LST). The comparison in the paper is presented as a growth-rate-vs-x
  curve (no single tabulated growth-rate digit is printed), so the verifiable
  anchor here is the SECOND-MODE INSTABILITY BAND and its most-amplified
  frequency at their stated station, not one printed number.

Web-confirmed conditions (June 2026)
------------------------------------
  Verified verbatim from the same group's companion / reproduction papers,
  which restate the identical Egorov-Fedorov-Soudakov base flow and cite the
  2006 paper as the source:

    * Novikov, Egorov & Fedorov, "Numerical simulation of wave packet evolution
      ..." (EUCASS): "perfect gas gamma=1.4, Pr=0.72, viscosity power law
      mu*/mu_inf* = (T*/T_inf*)^0.7, freestream Mach number M_inf=6, Reynolds
      number Re_inf = rho_inf* U_inf* L* / mu_inf* = 2x10^6, sharp-leading-edge
      flat plate, adiabatic wall (dTw/dy = 0)." Nondimensionalization uses the
      plate length L* and freestream state; omega = omega* L*/U_inf*.
    * Unnikrishnan & Gaitonde, "Linear, nonlinear and transitional regimes of
      second mode instability", Phys. Fluids / arXiv:2007.06726, reproduces the
      *same* case (their Ref. 23 == Egorov 2006): "freestream conditions
      correspond to Egorov et al., Re = 2x10^6, M_inf = 6 ... adiabatic flat
      plate ... the circular frequency of mode S is around omega_r = 200 in the
      vicinity of FS synchronization. Hence the actuator frequency is also
      chosen as omega_A = 200." The LST eigenspectrum is taken at x = 1 (local
      Re_x = Re_L * x = 2x10^6), and the linear second-mode response is obtained
      at small forcing amplitude A = 5e-4.

  So the pinnable LST point is: M=6 adiabatic flat plate, station x=1
  (R = sqrt(Re_x) = sqrt(2x10^6) ~ 1414), second mode (mode S) at the chosen
  dimensionless circular frequency omega_Egorov = 200.

Scale mapping (Egorov plate-length units -> Mack/pyMack units)
--------------------------------------------------------------
  Egorov: omega_E = omega* L*/U_inf*,  Re_L = rho U L*/mu = 2e6 (= Re_x at x=1).
  Mack F  = omega* nu_e/U_e^2.  Hence
      F = omega_E * (U/L*) * nu/U^2 = omega_E * nu/(U L*) = omega_E / Re_L
        = 200 / 2e6 = 1.0e-4.
  pyMack solver frequency at station R: omega_Mack = F * R = 1.0e-4 * 1414.2
        = 0.1414.
  pyMack station R = sqrt(Re_x) = sqrt(2e6) = 1414.2.

What is verified
----------------
  At M=6, adiabatic flat plate, power-law(0.7) viscosity, station R=1414.2,
  pyMack solve_spatial is swept over a band of frequencies bracketing
  omega_Egorov=200. We confirm: (a) the discrete SECOND mode (Mack mode,
  c_r ~ 0.92-0.94) is UNSTABLE (-alpha_i > 0) across Egorov's band; (b) the
  most-amplified frequency sits at omega_Egorov ~ 210 (F ~ 1.05e-4), i.e.
  within ~5% of Egorov's chosen omega=200; (c) at exactly omega=200 the spatial
  growth is -alpha_i ~ 2.9e-3 with c_r ~ 0.934. The metric scored is the
  relative offset of pyMack's most-amplified frequency from Egorov's omega=200.

Single-thread BLAS is forced (set BEFORE numpy import).
"""
